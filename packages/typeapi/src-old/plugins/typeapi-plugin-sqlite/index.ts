export interface SqlitePluginConfig {
  connectionString?: string;
}

// TODO: Should we separate this plugin into its own package?
export const SqlitePlugin = createPlugin<SqlitePluginConfig>(
  ({ connectionString = ':memory:' }) => ({
    pluginName: 'SqlitePlugin',
    onServerPreConfig: () => {
      const db = drizzle(new Database(connectionString));
      // TODO: Is there a better way to provide this context to our functions than global vars?
      globalThis.TypeApiPluginSqlite = {
        db,
      };
    },
  })
);

